ALTER PROCEDURE dbo.SP_CLEAR_COLOR_GUARDAR
 @Campo nvarchar(80),
 @Estado nvarchar(200),
 @Fondo nvarchar(7),
 @Texto nvarchar(7),
 @Usuario nvarchar(128),
 @Restablecer bit=0
AS
BEGIN
 SET NOCOUNT ON;
 SET XACT_ABORT ON;
 IF NULLIF(LTRIM(RTRIM(@Campo)),N'') IS NULL OR NULLIF(LTRIM(RTRIM(@Estado)),N'') IS NULL
  THROW 51031,N'Campo y estado obligatorios',1;
 IF NULLIF(LTRIM(RTRIM(@Usuario)),N'') IS NULL
  THROW 51032,N'Usuario obligatorio',1;
 IF @Restablecer=0 AND (
   @Fondo IS NULL OR @Texto IS NULL OR
   LEN(@Fondo)<>7 OR LEN(@Texto)<>7 OR
   LEFT(@Fondo,1)<>N'#' OR LEFT(@Texto,1)<>N'#' OR
   PATINDEX('%[^0-9A-Fa-f]%',SUBSTRING(@Fondo,2,6))>0 OR
   PATINDEX('%[^0-9A-Fa-f]%',SUBSTRING(@Texto,2,6))>0)
  THROW 51033,N'Los colores deben tener formato HEX #RRGGBB',1;
 DECLARE @AnteriorFondo nvarchar(7),@AnteriorTexto nvarchar(7);
 BEGIN TRY
  BEGIN TRANSACTION;
  SELECT @AnteriorFondo=COLOR_FONDO,@AnteriorTexto=COLOR_TEXTO
  FROM dbo.CLEAR_CONFIG_COLORES WITH(UPDLOCK,HOLDLOCK)
  WHERE MODULO=N'TELEMETRIA' AND CAMPO=@Campo AND ESTADO=@Estado;
  IF @Restablecer=1
  BEGIN
   IF @AnteriorFondo IS NOT NULL
    DELETE FROM dbo.CLEAR_CONFIG_COLORES
    WHERE MODULO=N'TELEMETRIA' AND CAMPO=@Campo AND ESTADO=@Estado;
  END
  ELSE IF @AnteriorFondo IS NULL
   INSERT dbo.CLEAR_CONFIG_COLORES(MODULO,CAMPO,ESTADO,COLOR_FONDO,COLOR_TEXTO,ACTUALIZADO_POR)
   VALUES(N'TELEMETRIA',@Campo,@Estado,UPPER(@Fondo),UPPER(@Texto),@Usuario);
  ELSE IF @AnteriorFondo<>@Fondo OR @AnteriorTexto<>@Texto
   UPDATE dbo.CLEAR_CONFIG_COLORES SET COLOR_FONDO=UPPER(@Fondo),COLOR_TEXTO=UPPER(@Texto),
    ACTUALIZADO_POR=@Usuario,ACTUALIZADO_EN=SYSDATETIME()
   WHERE MODULO=N'TELEMETRIA' AND CAMPO=@Campo AND ESTADO=@Estado;
  IF (@Restablecer=1 AND @AnteriorFondo IS NOT NULL) OR
     (@Restablecer=0 AND (@AnteriorFondo IS NULL OR @AnteriorFondo<>@Fondo OR @AnteriorTexto<>@Texto))
   INSERT dbo.CLEAR_CONFIG_COLORES_LOG(MODULO,CAMPO,ESTADO,ACCION,FONDO_ANTERIOR,TEXTO_ANTERIOR,FONDO_NUEVO,TEXTO_NUEVO,USUARIO)
   VALUES(N'TELEMETRIA',@Campo,@Estado,
    CASE WHEN @Restablecer=1 THEN N'RESTABLECER' ELSE N'GUARDAR' END,
    @AnteriorFondo,@AnteriorTexto,
    CASE WHEN @Restablecer=1 THEN NULL ELSE UPPER(@Fondo) END,
    CASE WHEN @Restablecer=1 THEN NULL ELSE UPPER(@Texto) END,@Usuario);
  COMMIT;
 END TRY
 BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK;
  THROW;
 END CATCH;
END;
GO
