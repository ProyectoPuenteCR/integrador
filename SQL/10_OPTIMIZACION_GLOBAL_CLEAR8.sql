SELECT A.*
FROM dbo.FIXALARMS A
WHERE NOT EXISTS
(
  SELECT 1 FROM dbo.CLEAR_ALARM_FILTERS F
  WHERE F.ACTIVO=1 AND
  (
    (F.CAMPO IN (N''TAG'',N''AMBOS'') AND
