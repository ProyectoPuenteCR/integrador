CREATE OR ALTER PROCEDURE dbo.SP_CLEAR_ACTUALIZAR_CACHE_OPERATIVA
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;
    SET DEADLOCK_PRIORITY LOW;

    DECLARE @ahora DATETIME2(0)=SYSDATETIME();
    DECLARE @lockResult INT;
    EXEC @lockResult=sys.sp_getapplock @Resource=N'CLEAR_CACHE_OPERATIVA',@LockMode=N'Exclusive',@LockOwner=N'Session',@LockTimeout=0;
    IF @lockResult<0 RETURN;

    CREATE TABLE #N
    (
        METRICA NVARCHAR(50) NOT NULL, ORDEN INT NOT NULL,
        DIMENSION1 NVARCHAR(500) NULL, DIMENSION2 NVARCHAR(500) NULL,
        VALOR1 DECIMAL(38,4) NULL, VALOR2 DECIMAL(38,4) NULL, VALOR3 DECIMAL(38,4) NULL,
        TEXTO1 NVARCHAR(1000) NULL, FECHA_CACHE DATETIME2(0) NOT NULL
    );

    SELECT
      A.ALM_NATIVETIMEIN,
      LTRIM(RTRIM(CONVERT(nvarchar(500),A.ALM_TAGNAME))) TAG,
      UPPER(LTRIM(RTRIM(CONVERT(nvarchar(100),A.ALM_ALMPRIORITY)))) PRIORIDAD,
      UPPER(LTRIM(RTRIM(CONVERT(nvarchar(255),A.ALM_ALMSTATUS)))) ESTADO,
      UPPER(LTRIM(RTRIM(CONVERT(nvarchar(500),A.ALM_VALUE)))) VALOR
    INTO #BASE7
    FROM dbo.CLEAR_F_FIXALARMS A
    WHERE A.ALM_NATIVETIMEIN>=DATEADD(day,-6,CONVERT(date,@ahora));

    CREATE CLUSTERED INDEX IX_BASE7_FECHA ON #BASE7(ALM_NATIVETIMEIN);
    SELECT * INTO #BASE24 FROM #BASE7 WHERE ALM_NATIVETIMEIN>=DATEADD(hour,-24,@ahora);

    INSERT #N VALUES(N'KPI',1,N'TOTAL24H',NULL,(SELECT COUNT_BIG(*) FROM #BASE24),NULL,NULL,NULL,@ahora);
    INSERT #N VALUES(N'KPI',2,N'TAGS_UNICOS24H',NULL,(SELECT COUNT_BIG(DISTINCT NULLIF(TAG,N'')) FROM #BASE24),NULL,NULL,NULL,@ahora);
    INSERT #N VALUES(N'KPI',3,N'CRITICAS',NULL,(SELECT COUNT_BIG(*) FROM #BASE24 WHERE PRIORIDAD IN (N'HIGH',N'HI',N'ALTA',N'CRITICAL',N'CRITICA',N'CRÍTICA')),NULL,NULL,NULL,@ahora);
    INSERT #N VALUES(N'KPI',4,N'ACTIVAS',NULL,(SELECT COUNT_BIG(*) FROM dbo.CLEAR_F_FIXALARMS_ONLY),NULL,NULL,NULL,@ahora);
    INSERT #N VALUES(N'KPI',5,N'RECONOCIDAS',NULL,(SELECT COUNT_BIG(*) FROM dbo.CLEAR_F_FIXALARMS_RECONOCIDAS),NULL,NULL,NULL,@ahora);
    INSERT #N VALUES(N'KPI',6,N'SUPRIMIDAS',NULL,(SELECT COUNT_BIG(*) FROM dbo.CLEAR_F_FIXALARMS_SUPRIMIDAS24H),NULL,NULL,NULL,@ahora);
    INSERT #N VALUES(N'KPI',7,N'COMENTADAS',NULL,(SELECT COUNT_BIG(*) FROM dbo.FIXALARMS_COMENTARIOS WHERE ACTIVO=1 AND COMENTARIO IS NOT NULL AND LTRIM(RTRIM(COMENTARIO))<>N''),NULL,NULL,NULL,@ahora);
    INSERT #N VALUES(N'KPI',8,N'ULTIMA_ALARMA',NULL,NULL,NULL,NULL,(SELECT TOP(1) CONVERT(nvarchar(19),ALM_NATIVETIMEIN,120) FROM #BASE7 ORDER BY ALM_NATIVETIMEIN DESC),@ahora);
    IF OBJECT_ID(N'dbo.POZOS') IS NOT NULL INSERT #N VALUES(N'KPI',9,N'POZOS',NULL,(SELECT COUNT_BIG(*) FROM dbo.POZOS),NULL,NULL,NULL,@ahora);
    IF OBJECT_ID(N'dbo.ALM_Importadas') IS NOT NULL INSERT #N VALUES(N'KPI',10,N'IMPORTADAS',NULL,(SELECT COUNT_BIG(*) FROM dbo.ALM_Importadas),NULL,NULL,NULL,@ahora);

    ;WITH T AS (SELECT TAG,COUNT_BIG(*) TOTAL FROM #BASE24 WHERE NULLIF(TAG,N'') IS NOT NULL GROUP BY TAG),
    R AS (SELECT ROW_NUMBER() OVER(ORDER BY TOTAL DESC,TAG) ORDEN,TAG,TOTAL FROM T)
    INSERT #N SELECT N'TOP_ALARMAS',ORDEN,TAG,NULL,TOTAL,NULL,NULL,NULL,@ahora FROM R WHERE ORDEN<=20;

    INSERT #N
    SELECT N'TENDENCIA',ROW_NUMBER() OVER(ORDER BY CONVERT(date,ALM_NATIVETIMEIN)),CONVERT(nvarchar(10),CONVERT(date,ALM_NATIVETIMEIN),23),NULL,COUNT_BIG(*),NULL,NULL,NULL,@ahora
    FROM #BASE7 GROUP BY CONVERT(date,ALM_NATIVETIMEIN);

    ;WITH P AS
    (
      SELECT CASE WHEN PRIORIDAD IN (N'HIGH',N'HI',N'ALTA',N'CRITICAL',N'CRITICA',N'CRÍTICA') THEN N'HIGH'
                  WHEN PRIORIDAD IN (N'MED',N'MEDIUM',N'MEDIA') THEN N'MEDIUM'
                  WHEN PRIORIDAD IN (N'LOW',N'LO',N'BAJA') THEN N'LOW' ELSE N'INFO' END CLASE,COUNT_BIG(*) TOTAL
      FROM #BASE24 GROUP BY CASE WHEN PRIORIDAD IN (N'HIGH',N'HI',N'ALTA',N'CRITICAL',N'CRITICA',N'CRÍTICA') THEN N'HIGH' WHEN PRIORIDAD IN (N'MED',N'MEDIUM',N'MEDIA') THEN N'MEDIUM' WHEN PRIORIDAD IN (N'LOW',N'LO',N'BAJA') THEN N'LOW' ELSE N'INFO' END
    ) INSERT #N SELECT N'PRIORIDAD',ROW_NUMBER() OVER(ORDER BY CLASE),CLASE,NULL,TOTAL,NULL,NULL,NULL,@ahora FROM P;

    ;WITH O AS (SELECT OPERADOR,COUNT_BIG(*) TOTAL FROM dbo.CLEAR_F_FIXALARMS_RECONOCIDAS WHERE OPERADOR IS NOT NULL GROUP BY OPERADOR),
    R AS (SELECT ROW_NUMBER() OVER(ORDER BY TOTAL DESC,OPERADOR) ORDEN,OPERADOR,TOTAL FROM O)
    INSERT #N SELECT N'OPERADORES',ORDEN,CONVERT(nvarchar(500),OPERADOR),NULL,TOTAL,NULL,NULL,NULL,@ahora FROM R WHERE ORDEN<=3;

    INSERT #N
    SELECT N'HORARIA',DATEPART(hour,ALM_NATIVETIMEIN)+1,CONVERT(nvarchar(2),DATEPART(hour,ALM_NATIVETIMEIN)),NULL,
      SUM(CASE WHEN PRIORIDAD IN (N'HIGH',N'HI',N'ALTA',N'CRITICAL',N'CRITICA',N'CRÍTICA') THEN 1 ELSE 0 END),
      SUM(CASE WHEN PRIORIDAD IN (N'MED',N'MEDIUM',N'MEDIA') THEN 1 ELSE 0 END),
      SUM(CASE WHEN PRIORIDAD NOT IN (N'HIGH',N'HI',N'ALTA',N'CRITICAL',N'CRITICA',N'CRÍTICA',N'MED',N'MEDIUM',N'MEDIA') THEN 1 ELSE 0 END),NULL,@ahora
    FROM #BASE24 GROUP BY DATEPART(hour,ALM_NATIVETIMEIN);

    INSERT #N
    SELECT N'FLUJO',DATEPART(hour,ALM_NATIVETIMEIN)+1,CONVERT(nvarchar(2),DATEPART(hour,ALM_NATIVETIMEIN)),NULL,
      SUM(CASE WHEN VALOR NOT IN (N'NORMAL',N'OK',N'HABILITADO') THEN 1 ELSE 0 END),
      SUM(CASE WHEN VALOR IN (N'NORMAL',N'OK',N'HABILITADO') THEN 1 ELSE 0 END),NULL,NULL,@ahora
    FROM #BASE24 GROUP BY DATEPART(hour,ALM_NATIVETIMEIN);

    INSERT #N
    SELECT N'HEATMAP',ROW_NUMBER() OVER(ORDER BY CONVERT(date,ALM_NATIVETIMEIN),DATEPART(hour,ALM_NATIVETIMEIN)),
      CONVERT(nvarchar(10),CONVERT(date,ALM_NATIVETIMEIN),23),CONVERT(nvarchar(2),DATEPART(hour,ALM_NATIVETIMEIN)),COUNT_BIG(*),NULL,NULL,NULL,@ahora
    FROM #BASE7 GROUP BY CONVERT(date,ALM_NATIVETIMEIN),DATEPART(hour,ALM_NATIVETIMEIN);

    ;WITH I AS
    (
      SELECT CASE WHEN CHARINDEX(N'_',TAG)>0 THEN LEFT(TAG,CHARINDEX(N'_',TAG)-1) ELSE TAG END INSTALACION,
        COUNT_BIG(*) TOTAL,SUM(CASE WHEN PRIORIDAD IN (N'HIGH',N'HI',N'ALTA',N'CRITICAL',N'CRITICA',N'CRÍTICA') THEN 1 ELSE 0 END) CRITICAS
      FROM #BASE24 WHERE NULLIF(TAG,N'') IS NOT NULL
      GROUP BY CASE WHEN CHARINDEX(N'_',TAG)>0 THEN LEFT(TAG,CHARINDEX(N'_',TAG)-1) ELSE TAG END
    ), R AS (SELECT ROW_NUMBER() OVER(ORDER BY TOTAL DESC,INSTALACION) ORDEN,* FROM I)
    INSERT #N SELECT N'INSTALACIONES',ORDEN,INSTALACION,NULL,TOTAL,CRITICAS,NULL,NULL,@ahora FROM R WHERE ORDEN<=8;

    INSERT #N SELECT N'FILTRO_ESTADO',ROW_NUMBER() OVER(ORDER BY E),E,NULL,NULL,NULL,NULL,NULL,@ahora
    FROM (SELECT DISTINCT ESTADO E FROM #BASE24 WHERE ESTADO IS NOT NULL) X WHERE E<>N'' AND E<>N'CFN';
    INSERT #N SELECT N'FILTRO_PRIORIDAD',ROW_NUMBER() OVER(ORDER BY P),P,NULL,NULL,NULL,NULL,NULL,@ahora
    FROM (SELECT DISTINCT PRIORIDAD P FROM #BASE24 WHERE PRIORIDAD IS NOT NULL) X WHERE P<>N'';
    INSERT #N SELECT N'FILTRO_INSTALACION',ROW_NUMBER() OVER(ORDER BY I),I,NULL,NULL,NULL,NULL,NULL,@ahora
    FROM (SELECT DISTINCT CASE WHEN CHARINDEX(N'_',TAG)>0 THEN LEFT(TAG,CHARINDEX(N'_',TAG)-1) ELSE TAG END I FROM #BASE24 WHERE NULLIF(TAG,N'') IS NOT NULL) X WHERE I<>N'';

    INSERT #N SELECT N'VALORES',ROW_NUMBER() OVER(ORDER BY VALOR),VALOR,NULL,COUNT_BIG(*),NULL,NULL,NULL,@ahora FROM #BASE24 WHERE VALOR IN (N'ALARMA',N'NORMAL',N'FALLA') GROUP BY VALOR;
    INSERT #N SELECT N'ESTADOS',ROW_NUMBER() OVER(ORDER BY ESTADO),ESTADO,NULL,COUNT_BIG(*),NULL,NULL,NULL,@ahora FROM #BASE24 WHERE ESTADO IN (N'OK',N'HI',N'LO') GROUP BY ESTADO;
    INSERT #N SELECT N'PRIORIDADES',ROW_NUMBER() OVER(ORDER BY P),P,NULL,COUNT_BIG(*),NULL,NULL,NULL,@ahora FROM (SELECT CASE WHEN PRIORIDAD IN (N'LOW',N'BAJA') THEN N'LOW' WHEN PRIORIDAD IN (N'CRITICAL',N'CRITICA',N'CRÍTICA') THEN N'CRITICAL' ELSE PRIORIDAD END P FROM #BASE24) X WHERE P IN (N'LOW',N'CRITICAL',N'INFO') GROUP BY P;

    BEGIN TRY
      BEGIN TRANSACTION;
        TRUNCATE TABLE dbo.CLEAR_CACHE_OPERATIVA;
        INSERT dbo.CLEAR_CACHE_OPERATIVA SELECT * FROM #N;
      COMMIT TRANSACTION;
    END TRY
    BEGIN CATCH
      IF @@TRANCOUNT>0 ROLLBACK TRANSACTION;
      EXEC sys.sp_releaseapplock @Resource=N'CLEAR_CACHE_OPERATIVA',@LockOwner=N'Session';
      THROW;
    END CATCH;
    EXEC sys.sp_releaseapplock @Resource=N'CLEAR_CACHE_OPERATIVA',@LockOwner=N'Session';
END;
GO

EXEC dbo.SP_CLEAR_ACTUALIZAR_CACHE_OPERATIVA;
GO

