BEGIN
    CREATE TABLE dbo.CLEAR_ALARM_FILTERS
    (
        ID INT IDENTITY(1,1) NOT NULL CONSTRAINT PK_CLEAR_ALARM_FILTERS PRIMARY KEY,
        CAMPO NVARCHAR(20) NOT NULL CONSTRAINT DF_CLEAR_ALARM_FILTERS_CAMPO DEFAULT N'AMBOS',
        MODO NVARCHAR(20) NOT NULL CONSTRAINT DF_CLEAR_ALARM_FILTERS_MODO DEFAULT N'CONTIENE',
        VALOR NVARCHAR(500) NOT NULL,
        ACTIVO BIT NOT NULL CONSTRAINT DF_CLEAR_ALARM_FILTERS_ACTIVO DEFAULT (1),
        FECHA_ALTA DATETIME2(0) NOT NULL CONSTRAINT DF_CLEAR_ALARM_FILTERS_FECHA DEFAULT SYSDATETIME(),
        USUARIO_ALTA NVARCHAR(128) NULL
    );
END;
