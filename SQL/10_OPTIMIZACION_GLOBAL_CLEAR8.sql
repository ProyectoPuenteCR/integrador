/*
  CLEAR 8 - OPTIMIZACION GLOBAL
  =============================
  - dbo.FIXALARMS permanece exclusivamente en modo lectura.
  - No agrega columnas, índices ni triggers a dbo.FIXALARMS.
  - Los objetos DDL se instalan una sola vez; PHP deja de ejecutar ALTER VIEW.
  - Materializa indicadores operativos cada 5 minutos en una tabla CLEAR.
