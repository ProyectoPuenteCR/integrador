 Dia operativo inicial 00:00, configurable mediante SP_CLEAR_DASH_POZOS_CONFIGURAR.
 El inicio sin comunicacion es OBSERVADO, nunca se deduce de FECHA_CACHE ni de
 ULTIMA_ACTUALIZACION como si fuesen el inicio real de una falla anterior.
