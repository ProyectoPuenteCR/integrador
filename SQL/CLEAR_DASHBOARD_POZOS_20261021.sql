CREATE OR ALTER FUNCTION dbo.FN_CLEAR_DASH_POZO_CLAVE(@Pozo nvarchar(255))
RETURNS nvarchar(100)
WITH SCHEMABINDING
AS
BEGIN
 DECLARE @s nvarchar(255)=UPPER(LTRIM(RTRIM(ISNULL(@Pozo,N''))));
 SET @s=REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(@s,
  N'Á',N'A'),N'É',N'E'),N'Í',N'I'),N'Ó',N'O'),N'Ú',N'U'),N'Ü',N'U'),N'Ñ',N'N');
 SET @s=REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(@s,N'.',N''),N'-',N''),N'_',N''),N' ',N''),N'/',N'');
 IF LEFT(@s,5)=N'YPFSC' SET @s=SUBSTRING(@s,6,250);
 RETURN LEFT(@s,100);
END;
GO
CREATE OR ALTER FUNCTION dbo.FN_CLEAR_DASH_COMUNICACION(@Valor nvarchar(255))
RETURNS nvarchar(30)
WITH SCHEMABINDING
AS
BEGIN
 DECLARE @s nvarchar(255)=UPPER(LTRIM(RTRIM(ISNULL(@Valor,N''))));
 IF @s=N'' RETURN N'Sin dato';
 IF @s=N'0' OR @s LIKE N'%BAD%' OR @s LIKE N'%FALL%' OR @s LIKE N'%NO DATA%'
  OR @s LIKE N'%DESC%' OR @s LIKE N'%ERROR%' OR @s LIKE N'%SIN COM%'
  OR @s LIKE N'%NO COM%' OR @s LIKE N'%OFFLINE%' RETURN N'Sin comunicación';
 IF @s LIKE N'%INTER%' OR @s LIKE N'%DEMOR%' OR @s LIKE N'%WARN%' RETURN N'Intermitente';
 IF @s IN(N'1',N'ON',N'OK') OR @s LIKE N'%NORMAL%' OR @s LIKE N'%GOOD%'
  OR @s LIKE N'%COMUNIC%' OR @s LIKE N'%ONLINE%' OR @s LIKE N'%HOST%' RETURN N'Comunicando';
 RETURN N'Sin dato';
END;
GO
CREATE OR ALTER FUNCTION dbo.FN_CLEAR_DASH_ESTADO(@Valor nvarchar(255))
RETURNS nvarchar(30)
WITH SCHEMABINDING
AS
BEGIN
 DECLARE @s nvarchar(255)=UPPER(LTRIM(RTRIM(ISNULL(@Valor,N''))));
 SET @s=REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(@s,N'Á',N'A'),N'É',N'E'),N'Í',N'I'),N'Ó',N'O'),N'Ú',N'U');
 /* Se quitan negaciones antes de buscar fallas: SIN FALLA no es FALLA. */
 SET @s=REPLACE(REPLACE(REPLACE(REPLACE(@s,N'SIN FALLAS',N''),N'NO FALLAS',N''),N'SIN FALLA',N''),N'NO FALLA',N'');
 SET @s=REPLACE(REPLACE(REPLACE(REPLACE(@s,N'SIN ERRORES',N''),N'NO ERRORES',N''),N'SIN ERROR',N''),N'NO ERROR',N'');
 SET @s=REPLACE(REPLACE(REPLACE(REPLACE(@s,N'SIN ALARMAS',N''),N'NO ALARMAS',N''),N'SIN ALARMA',N''),N'NO ALARMA',N'');
 SET @s=REPLACE(REPLACE(REPLACE(REPLACE(@s,N'SIN FAULTS',N''),N'NO FAULTS',N''),N'SIN FAULT',N''),N'NO FAULT',N'');
 IF @s LIKE N'%FALL%' OR @s LIKE N'%FAULT%' OR @s LIKE N'%ALAR%' OR @s LIKE N'%ERROR%'
  OR @s LIKE N'%EMER%' OR @s LIKE N'%TRIP%' OR @s LIKE N'%DEFECT%' RETURN N'En falla';
 IF @s LIKE N'%PARO%' OR @s LIKE N'%PARAD%' OR @s LIKE N'%STOP%' OR @s LIKE N'%OFF%'
  OR @s LIKE N'%INACT%' OR @s LIKE N'%DETEN%' RETURN N'Parado';
 IF @s LIKE N'%MARCH%' OR @s LIKE N'%NORMAL%' OR @s LIKE N'%OPER%' OR @s LIKE N'%RUN%'
  OR @s LIKE N'%BOMB%' OR @s LIKE N'%OK%' RETURN N'En marcha';
 RETURN N'Desconocido';
END;
GO
CREATE OR ALTER PROCEDURE dbo.SP_CLEAR_DASH_POZOS_CONFIGURAR
 @HoraCorte time(0),@RetencionDias smallint=400,@MaxAntiguedadMin smallint=30
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;
 IF @HoraCorte IS NULL OR @RetencionDias NOT BETWEEN 70 AND 730 OR @MaxAntiguedadMin NOT BETWEEN 10 AND 120
  THROW 51201,N'Configuracion invalida: retencion 70..730 dias; antiguedad 10..120 minutos.',1;
 /* Los cierres antiguos conservan su HORA_CORTE. PHP no mezcla cortes distintos. */
 UPDATE dbo.CLEAR_DASH_POZOS_CONFIG SET HORA_CORTE=@HoraCorte,RETENCION_DIAS=@RetencionDias,
  MAX_ANTIGUEDAD_MIN=@MaxAntiguedadMin,FECHA_CAMBIO=SYSDATETIME() WHERE ID=1;
END;
GO
CREATE OR ALTER PROCEDURE dbo.SP_CLEAR_DASH_POZOS_REFRESCAR
AS
BEGIN
 SET NOCOUNT ON;SET XACT_ABORT ON;SET DEADLOCK_PRIORITY LOW;SET LOCK_TIMEOUT 5000;
 DECLARE @Ahora datetime2(0)=SYSDATETIME(),@Corte time(0),@Dias smallint,@Edad smallint,@Lock int,
  @Mensaje nvarchar(2000)=N'',@FallasOk bit=0,@Foto datetime2(0),@Anterior datetime2(0),
  @TelemetriaOk bit=0,@Completa bit=1,@Dia date,@Desde datetime2(0),@Hasta datetime2(0),@SegCorte int;
 SELECT @Corte=HORA_CORTE,@Dias=RETENCION_DIAS,@Edad=MAX_ANTIGUEDAD_MIN FROM dbo.CLEAR_DASH_POZOS_CONFIG WHERE ID=1;
 SET @SegCorte=DATEDIFF(second,CONVERT(time(0),'00:00:00'),@Corte);
 SET @Dia=CONVERT(date,DATEADD(second,-@SegCorte,@Ahora));
 SET @Desde=DATEADD(second,@SegCorte,CONVERT(datetime2(0),@Dia));
 SET @Hasta=DATEADD(day,1,@Desde);
 EXEC @Lock=sys.sp_getapplock @Resource=N'CLEAR_DASH_POZOS_REFRESCAR',@LockMode=N'Exclusive',@LockOwner=N'Session',@LockTimeout=0;
 IF @Lock<0 RETURN;
 BEGIN TRY
  CREATE TABLE #Fallas(
   DIA_OPERATIVO date NOT NULL,POZO_CLAVE nvarchar(100) COLLATE DATABASE_DEFAULT NOT NULL,
   POZO nvarchar(255) COLLATE DATABASE_DEFAULT NOT NULL,TAG nvarchar(255) COLLATE DATABASE_DEFAULT NOT NULL,
   DETALLE_FALLA nvarchar(1000) COLLATE DATABASE_DEFAULT NULL,CANT_FALLAS bigint NOT NULL,
   PRIMERA_FALLA datetime2(0) NOT NULL,ULTIMA_FALLA datetime2(0) NOT NULL,
   PRIMARY KEY(DIA_OPERATIVO,POZO_CLAVE,TAG));
  /* La fuente de ocurrencias se lee una vez y solo en el rango del dia.
     Se prefiere la cache 7d si expone los campos y una fecha de carga reciente.
     El fallback conocido es la vista filtrada local; nunca consultas PI/RTQP. */
  BEGIN TRY
   DECLARE @Fuente sysname,@FuenteFecha sysname,@UltimaFuente datetime2(0),@Sql nvarchar(max),@Filtro nvarchar(max)=N'';
   IF OBJECT_ID(N'dbo.CLEAR_ALARMAS_CACHE_7D',N'U') IS NOT NULL
    AND COL_LENGTH(N'dbo.CLEAR_ALARMAS_CACHE_7D',N'ALM_VALUE') IS NOT NULL
    AND COL_LENGTH(N'dbo.CLEAR_ALARMAS_CACHE_7D',N'ALM_NATIVETIMEIN') IS NOT NULL
    AND COL_LENGTH(N'dbo.CLEAR_ALARMAS_CACHE_7D',N'ALM_ALMEXTFLD2') IS NOT NULL
    AND COL_LENGTH(N'dbo.CLEAR_ALARMAS_CACHE_7D',N'ALM_TAGNAME') IS NOT NULL
    AND COL_LENGTH(N'dbo.CLEAR_ALARMAS_CACHE_7D',N'ALM_DESCR') IS NOT NULL
    AND COL_LENGTH(N'dbo.CLEAR_ALARMAS_CACHE_7D',N'ALM_ALMSTATUS') IS NOT NULL
   BEGIN
    SELECT TOP(1) @FuenteFecha=name FROM sys.columns
    WHERE object_id=OBJECT_ID(N'dbo.CLEAR_ALARMAS_CACHE_7D') AND name IN(N'FECHA_CACHE',N'FECHA_ACTUALIZACION') ORDER BY name;
    IF @FuenteFecha IS NOT NULL
    BEGIN
     SET @Sql=N'SELECT @F=MAX(TRY_CONVERT(datetime2(0),'+QUOTENAME(@FuenteFecha)+N')) FROM dbo.CLEAR_ALARMAS_CACHE_7D;';
     EXEC sys.sp_executesql @Sql,N'@F datetime2(0) OUTPUT',@F=@UltimaFuente OUTPUT;
     IF @UltimaFuente>=DATEADD(minute,-@Edad,@Ahora) AND @UltimaFuente<=@Ahora SET @Fuente=N'CLEAR_ALARMAS_CACHE_7D';
    END;
   END;
   IF @Fuente IS NULL AND OBJECT_ID(N'dbo.CLEAR_F_FIXALARMS',N'V') IS NOT NULL SET @Fuente=N'CLEAR_F_FIXALARMS';
   IF @Fuente IS NULL AND OBJECT_ID(N'dbo.FIXALARMS',N'U') IS NOT NULL SET @Fuente=N'FIXALARMS';
   IF @Fuente IS NULL THROW 51202,N'No se encontro una fuente local de ocurrencias de falla.',1;
   IF COL_LENGTH(N'dbo.'+@Fuente,N'ALM_VALUE') IS NULL OR COL_LENGTH(N'dbo.'+@Fuente,N'ALM_ALMEXTFLD2') IS NULL
    OR COL_LENGTH(N'dbo.'+@Fuente,N'ALM_NATIVETIMEIN') IS NULL
    THROW 51203,N'La fuente local no posee ALM_VALUE/ALM_ALMEXTFLD2/ALM_NATIVETIMEIN.',1;
   IF @Fuente<>N'CLEAR_F_FIXALARMS'
   BEGIN
    IF OBJECT_ID(N'dbo.CLEAR_ALARM_POLICY',N'U') IS NOT NULL AND COL_LENGTH(N'dbo.'+@Fuente,N'ALM_ALMSTATUS') IS NOT NULL
     SET @Filtro+=N' AND NOT EXISTS(SELECT 1 FROM dbo.CLEAR_ALARM_POLICY P WHERE P.ID=1 AND P.MODO_ACTIVO=N''EXCLUIR'' AND UPPER(LTRIM(RTRIM(CONVERT(nvarchar(100),A.ALM_ALMSTATUS))))=N''CFN'')';
    IF OBJECT_ID(N'dbo.CLEAR_ALARM_FILTERS',N'U') IS NOT NULL
     SET @Filtro+=N' AND NOT EXISTS(SELECT 1 FROM dbo.CLEAR_ALARM_FILTERS F WHERE F.ACTIVO=1 AND
      ((F.CAMPO IN(N''TAG'',N''AMBOS'') AND
       ((F.MODO=N''EXACTO'' AND LTRIM(RTRIM(CONVERT(nvarchar(1000),A.ALM_TAGNAME))) COLLATE DATABASE_DEFAULT=F.VALOR COLLATE DATABASE_DEFAULT)
       OR (F.MODO=N''COMIENZA'' AND CONVERT(nvarchar(1000),A.ALM_TAGNAME) COLLATE DATABASE_DEFAULT LIKE (F.VALOR+N''%'') COLLATE DATABASE_DEFAULT)
       OR (F.MODO=N''CONTIENE'' AND CONVERT(nvarchar(1000),A.ALM_TAGNAME) COLLATE DATABASE_DEFAULT LIKE (N''%''+F.VALOR+N''%'') COLLATE DATABASE_DEFAULT)))
      OR (F.CAMPO IN(N''DESCRIPCION'',N''AMBOS'') AND
       ((F.MODO=N''EXACTO'' AND LTRIM(RTRIM(CONVERT(nvarchar(1000),A.ALM_DESCR))) COLLATE DATABASE_DEFAULT=F.VALOR COLLATE DATABASE_DEFAULT)
       OR (F.MODO=N''COMIENZA'' AND CONVERT(nvarchar(1000),A.ALM_DESCR) COLLATE DATABASE_DEFAULT LIKE (F.VALOR+N''%'') COLLATE DATABASE_DEFAULT)
       OR (F.MODO=N''CONTIENE'' AND CONVERT(nvarchar(1000),A.ALM_DESCR) COLLATE DATABASE_DEFAULT LIKE (N''%''+F.VALOR+N''%'') COLLATE DATABASE_DEFAULT)))))';
   END;
   SET @Sql=N'INSERT #Fallas(DIA_OPERATIVO,POZO_CLAVE,POZO,TAG,DETALLE_FALLA,CANT_FALLAS,PRIMERA_FALLA,ULTIMA_FALLA)
    SELECT @Dia,dbo.FN_CLEAR_DASH_POZO_CLAVE(CONVERT(nvarchar(255),A.ALM_ALMEXTFLD2)),
     MAX(LTRIM(RTRIM(CONVERT(nvarchar(255),A.ALM_ALMEXTFLD2)))),
     COALESCE(LTRIM(RTRIM(CONVERT(nvarchar(255),A.ALM_TAGNAME))),N''''),
     MAX(COALESCE(NULLIF(LTRIM(RTRIM(CONVERT(nvarchar(1000),A.ALM_DESCR))),N''''),CONVERT(nvarchar(1000),A.ALM_TAGNAME))),
     COUNT_BIG(*),MIN(CONVERT(datetime2(0),A.ALM_NATIVETIMEIN)),MAX(CONVERT(datetime2(0),A.ALM_NATIVETIMEIN))
    FROM dbo.'+QUOTENAME(@Fuente)+N' A
    WHERE A.ALM_NATIVETIMEIN>=@Desde AND A.ALM_NATIVETIMEIN<@Hasta AND A.ALM_NATIVETIMEIN<=@Ahora
     AND UPPER(LTRIM(RTRIM(CONVERT(nvarchar(255),A.ALM_VALUE)))) IN(N''FALLA'',N''FAULT'')
     AND dbo.FN_CLEAR_DASH_POZO_CLAVE(CONVERT(nvarchar(255),A.ALM_ALMEXTFLD2))<>N'''''+@Filtro+N'
    GROUP BY dbo.FN_CLEAR_DASH_POZO_CLAVE(CONVERT(nvarchar(255),A.ALM_ALMEXTFLD2)),
     COALESCE(LTRIM(RTRIM(CONVERT(nvarchar(255),A.ALM_TAGNAME))),N'''') OPTION(MAXDOP 1,RECOMPILE);';
   EXEC sys.sp_executesql @Sql,N'@Dia date,@Desde datetime2(0),@Hasta datetime2(0),@Ahora datetime2(0)',@Dia,@Desde,@Hasta,@Ahora;
   SET @FallasOk=1;
  END TRY
  BEGIN CATCH
   SET @Mensaje=LEFT(N'Fallas del dia: '+ERROR_MESSAGE(),2000);
  END CATCH;

  CREATE TABLE #Raw(
   POZO_CLAVE nvarchar(100) COLLATE DATABASE_DEFAULT NOT NULL,POZO nvarchar(255) COLLATE DATABASE_DEFAULT NOT NULL,
   BATERIA nvarchar(255) COLLATE DATABASE_DEFAULT NULL,TIPO nvarchar(20) COLLATE DATABASE_DEFAULT NULL,
   COMUNICACION nvarchar(30) COLLATE DATABASE_DEFAULT NOT NULL,ESTADO nvarchar(30) COLLATE DATABASE_DEFAULT NOT NULL,
   DETALLE_ESTADO nvarchar(255) COLLATE DATABASE_DEFAULT NULL,FECHA_CACHE datetime2(0) NULL,FRESCO bit NOT NULL);
  IF OBJECT_ID(N'dbo.TELEMETRIA_POZOS_GENERAL_CACHE',N'U') IS NOT NULL
  BEGIN
   INSERT #Raw
   SELECT dbo.FN_CLEAR_DASH_POZO_CLAVE(CONVERT(nvarchar(255),POZO)),LTRIM(RTRIM(CONVERT(nvarchar(255),POZO))),
    NULLIF(LTRIM(RTRIM(CONVERT(nvarchar(255),BATERIA))),N''),
    CASE WHEN UPPER(LTRIM(RTRIM(CONVERT(nvarchar(20),TIPO)))) IN(N'TECSS',N'TECCS') THEN N'TECSS' ELSE N'SCADA' END,
    dbo.FN_CLEAR_DASH_COMUNICACION(CONVERT(nvarchar(255),COMUNICACION)),dbo.FN_CLEAR_DASH_ESTADO(CONVERT(nvarchar(255),ESTADO)),
    NULLIF(LTRIM(RTRIM(CONVERT(nvarchar(255),ESTADO))),N''),TRY_CONVERT(datetime2(0),FECHA_CACHE),0
   FROM dbo.TELEMETRIA_POZOS_GENERAL_CACHE WHERE POZO IS NOT NULL AND LTRIM(RTRIM(CONVERT(nvarchar(255),POZO)))<>N''
   OPTION(MAXDOP 1);
   /* Medir despues de leer: el job general pudo refrescar mientras se contaban
      las fallas. Su nueva fecha no debe confundirse con una fecha futura. */
   DECLARE @Observado datetime2(0)=SYSDATETIME();
   UPDATE #Raw SET FRESCO=CASE WHEN FECHA_CACHE>=DATEADD(minute,-@Edad,@Observado)
     AND FECHA_CACHE<=@Observado THEN 1 ELSE 0 END,
    FECHA_CACHE=CASE WHEN FECHA_CACHE<=@Observado THEN FECHA_CACHE END;
   DELETE FROM #Raw WHERE POZO_CLAVE=N'';
   /* Un alias antiguo de la misma fuente no prolonga una falla ya recuperada.
      Empates en la ultima foto conservan la prioridad de estado establecida. */
   ;WITH Ultimas AS(
    SELECT *,MAX(FECHA_CACHE) OVER(PARTITION BY POZO_CLAVE,TIPO) AS FECHA_MAX FROM #Raw
   ) DELETE FROM Ultimas WHERE FECHA_CACHE<FECHA_MAX OR (FECHA_CACHE IS NULL AND FECHA_MAX IS NOT NULL);
   SELECT @Foto=MAX(FECHA_CACHE),@Completa=CONVERT(bit,MIN(CONVERT(int,FRESCO))) FROM #Raw;
   IF EXISTS(SELECT 1 FROM #Raw WHERE FRESCO=1) SET @TelemetriaOk=1;
  END;
  IF @TelemetriaOk=0 SET @Mensaje=LEFT(@Mensaje+CASE WHEN @Mensaje=N'' THEN N'' ELSE N' · ' END+
   N'Telemetria ausente o antigua: se conserva la ultima foto; no se completa historia.',2000);

  CREATE TABLE #Nueva(
   POZO_CLAVE nvarchar(100) COLLATE DATABASE_DEFAULT NOT NULL PRIMARY KEY,
   POZO nvarchar(255) COLLATE DATABASE_DEFAULT NOT NULL,BATERIA nvarchar(255) COLLATE DATABASE_DEFAULT NULL,
   TIPO nvarchar(30) COLLATE DATABASE_DEFAULT NOT NULL,EN_SCADA bit NOT NULL,EN_TECSS bit NOT NULL,
   COMUNICACION nvarchar(30) COLLATE DATABASE_DEFAULT NOT NULL,ESTADO nvarchar(30) COLLATE DATABASE_DEFAULT NOT NULL,
   SCADA_COMUNICACION nvarchar(30) COLLATE DATABASE_DEFAULT NULL,TECSS_COMUNICACION nvarchar(30) COLLATE DATABASE_DEFAULT NULL,
   SCADA_ESTADO nvarchar(30) COLLATE DATABASE_DEFAULT NULL,TECSS_ESTADO nvarchar(30) COLLATE DATABASE_DEFAULT NULL,
   DETALLE_ESTADO nvarchar(255) COLLATE DATABASE_DEFAULT NULL,FECHA_CACHE datetime2(0) NOT NULL);
  IF @TelemetriaOk=1
  BEGIN
   INSERT #Nueva
   SELECT POZO_CLAVE,MIN(POZO),MAX(BATERIA),
    CASE WHEN MAX(CASE WHEN TIPO IN(N'TECSS',N'TECCS') THEN 1 ELSE 0 END)=1
      THEN CASE WHEN MAX(CASE WHEN TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL THEN 1 ELSE 0 END)=1
        THEN N'SCADA / TECSS' ELSE N'TECSS' END ELSE N'SCADA' END,
    MAX(CASE WHEN TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL THEN 1 ELSE 0 END),
    MAX(CASE WHEN TIPO IN(N'TECSS',N'TECCS') THEN 1 ELSE 0 END),
    CASE WHEN MAX(CASE WHEN FRESCO=1 AND COMUNICACION=N'Comunicando' THEN 1 ELSE 0 END)=1 THEN N'Comunicando'
     WHEN MAX(CASE WHEN FRESCO=1 AND COMUNICACION=N'Intermitente' THEN 1 ELSE 0 END)=1 THEN N'Intermitente'
     WHEN MAX(CASE WHEN FRESCO=1 AND COMUNICACION=N'Sin comunicación' THEN 1 ELSE 0 END)=1 THEN N'Sin comunicación' ELSE N'Sin dato' END,
    CASE WHEN MAX(CASE WHEN FRESCO=1 AND ESTADO=N'En falla' THEN 1 ELSE 0 END)=1 THEN N'En falla'
     WHEN MAX(CASE WHEN FRESCO=1 AND ESTADO=N'Parado' THEN 1 ELSE 0 END)=1 THEN N'Parado'
     WHEN MAX(CASE WHEN FRESCO=1 AND ESTADO=N'En marcha' THEN 1 ELSE 0 END)=1 THEN N'En marcha' ELSE N'Desconocido' END,
    CASE WHEN MAX(CASE WHEN TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL THEN 1 ELSE 0 END)=0 THEN NULL
     WHEN MAX(CASE WHEN FRESCO=1 AND (TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL) AND COMUNICACION=N'Comunicando' THEN 1 ELSE 0 END)=1 THEN N'Comunicando'
     WHEN MAX(CASE WHEN FRESCO=1 AND (TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL) AND COMUNICACION=N'Intermitente' THEN 1 ELSE 0 END)=1 THEN N'Intermitente'
     WHEN MAX(CASE WHEN FRESCO=1 AND (TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL) AND COMUNICACION=N'Sin comunicación' THEN 1 ELSE 0 END)=1 THEN N'Sin comunicación' ELSE N'Sin dato' END,
    CASE WHEN MAX(CASE WHEN TIPO IN(N'TECSS',N'TECCS') THEN 1 ELSE 0 END)=0 THEN NULL
     WHEN MAX(CASE WHEN FRESCO=1 AND TIPO IN(N'TECSS',N'TECCS') AND COMUNICACION=N'Comunicando' THEN 1 ELSE 0 END)=1 THEN N'Comunicando'
     WHEN MAX(CASE WHEN FRESCO=1 AND TIPO IN(N'TECSS',N'TECCS') AND COMUNICACION=N'Intermitente' THEN 1 ELSE 0 END)=1 THEN N'Intermitente'
     WHEN MAX(CASE WHEN FRESCO=1 AND TIPO IN(N'TECSS',N'TECCS') AND COMUNICACION=N'Sin comunicación' THEN 1 ELSE 0 END)=1 THEN N'Sin comunicación' ELSE N'Sin dato' END,
    CASE WHEN MAX(CASE WHEN TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL THEN 1 ELSE 0 END)=0 THEN NULL
     WHEN MAX(CASE WHEN FRESCO=1 AND (TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL) AND ESTADO=N'En falla' THEN 1 ELSE 0 END)=1 THEN N'En falla'
     WHEN MAX(CASE WHEN FRESCO=1 AND (TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL) AND ESTADO=N'Parado' THEN 1 ELSE 0 END)=1 THEN N'Parado'
     WHEN MAX(CASE WHEN FRESCO=1 AND (TIPO NOT IN(N'TECSS',N'TECCS') OR TIPO IS NULL) AND ESTADO=N'En marcha' THEN 1 ELSE 0 END)=1 THEN N'En marcha' ELSE N'Desconocido' END,
    CASE WHEN MAX(CASE WHEN TIPO IN(N'TECSS',N'TECCS') THEN 1 ELSE 0 END)=0 THEN NULL
     WHEN MAX(CASE WHEN FRESCO=1 AND TIPO IN(N'TECSS',N'TECCS') AND ESTADO=N'En falla' THEN 1 ELSE 0 END)=1 THEN N'En falla'
     WHEN MAX(CASE WHEN FRESCO=1 AND TIPO IN(N'TECSS',N'TECCS') AND ESTADO=N'Parado' THEN 1 ELSE 0 END)=1 THEN N'Parado'
     WHEN MAX(CASE WHEN FRESCO=1 AND TIPO IN(N'TECSS',N'TECCS') AND ESTADO=N'En marcha' THEN 1 ELSE 0 END)=1 THEN N'En marcha' ELSE N'Desconocido' END,
    COALESCE(MAX(CASE WHEN FRESCO=1 AND ESTADO=N'En falla' THEN DETALLE_ESTADO END),MAX(DETALLE_ESTADO)),
    /* Una fuente sin fecha conserva el pozo como Sin dato/Desconocido.
       La fecha de foto es observacion, nunca inicio de falta de comunicacion. */
    COALESCE(MAX(FECHA_CACHE),@Foto)
   FROM #Raw GROUP BY POZO_CLAVE OPTION(MAXDOP 1);
  END;

  BEGIN TRANSACTION;
   IF @FallasOk=1
   BEGIN
    DELETE FROM dbo.CLEAR_DASH_POZOS_FALLAS_DIA WHERE DIA_OPERATIVO=@Dia;
    INSERT dbo.CLEAR_DASH_POZOS_FALLAS_DIA
     (DIA_OPERATIVO,POZO_CLAVE,POZO,TAG,DETALLE_FALLA,CANT_FALLAS,PRIMERA_FALLA,ULTIMA_FALLA,FECHA_CACHE)
    SELECT DIA_OPERATIVO,POZO_CLAVE,POZO,TAG,DETALLE_FALLA,CANT_FALLAS,PRIMERA_FALLA,ULTIMA_FALLA,@Ahora FROM #Fallas;
   END;
   SELECT @Anterior=FECHA_TELEMETRIA FROM dbo.CLEAR_DASH_POZOS_ESTADO_FUENTES WHERE ID=1;
   IF @TelemetriaOk=1 AND (@Anterior IS NULL OR @Foto>@Anterior)
   BEGIN
    /* La continuidad se pierde con brechas o desaparicion. El nuevo inicio queda
       estimado; nunca se usa la fecha de carga como inicio de una falla pasada. */
    UPDATE T SET
     SIN_COM_DESDE=CASE WHEN N.COMUNICACION<>N'Sin comunicación' THEN NULL
       WHEN T.COMUNICACION=N'Sin comunicación' AND T.SIN_COM_DESDE IS NOT NULL
        AND DATEDIFF(second,T.FECHA_CACHE,N.FECHA_CACHE)<=@Edad*60 THEN T.SIN_COM_DESDE ELSE N.FECHA_CACHE END,
     SIN_COM_INICIO_ESTIMADO=CASE WHEN N.COMUNICACION<>N'Sin comunicación' THEN 0
       WHEN DATEDIFF(second,T.FECHA_CACHE,N.FECHA_CACHE)>@Edad*60 THEN 1
       WHEN T.COMUNICACION=N'Sin comunicación' THEN T.SIN_COM_INICIO_ESTIMADO
       WHEN T.COMUNICACION IN(N'Comunicando',N'Intermitente') THEN 0 ELSE 1 END,
     POZO=N.POZO,BATERIA=N.BATERIA,TIPO=N.TIPO,EN_SCADA=N.EN_SCADA,EN_TECSS=N.EN_TECSS,
     COMUNICACION=N.COMUNICACION,ESTADO=N.ESTADO,
     SCADA_COMUNICACION=N.SCADA_COMUNICACION,TECSS_COMUNICACION=N.TECSS_COMUNICACION,
     SCADA_ESTADO=N.SCADA_ESTADO,TECSS_ESTADO=N.TECSS_ESTADO,
     DETALLE_ESTADO=N.DETALLE_ESTADO,FECHA_CACHE=N.FECHA_CACHE
    FROM dbo.CLEAR_DASH_POZOS_ACTUAL T INNER JOIN #Nueva N ON N.POZO_CLAVE=T.POZO_CLAVE
    WHERE N.FECHA_CACHE>=T.FECHA_CACHE;
    INSERT dbo.CLEAR_DASH_POZOS_ACTUAL
     (POZO_CLAVE,POZO,BATERIA,TIPO,EN_SCADA,EN_TECSS,COMUNICACION,ESTADO,SCADA_COMUNICACION,TECSS_COMUNICACION,
      SCADA_ESTADO,TECSS_ESTADO,DETALLE_ESTADO,FECHA_CACHE,SIN_COM_DESDE,SIN_COM_INICIO_ESTIMADO)
    SELECT N.POZO_CLAVE,N.POZO,N.BATERIA,N.TIPO,N.EN_SCADA,N.EN_TECSS,N.COMUNICACION,N.ESTADO,
     N.SCADA_COMUNICACION,N.TECSS_COMUNICACION,N.SCADA_ESTADO,N.TECSS_ESTADO,N.DETALLE_ESTADO,N.FECHA_CACHE,
     CASE WHEN N.COMUNICACION=N'Sin comunicación' THEN N.FECHA_CACHE END,
     CASE WHEN N.COMUNICACION=N'Sin comunicación' THEN 1 ELSE 0 END
    FROM #Nueva N WHERE NOT EXISTS(SELECT 1 FROM dbo.CLEAR_DASH_POZOS_ACTUAL T WHERE T.POZO_CLAVE=N.POZO_CLAVE);
    DELETE T FROM dbo.CLEAR_DASH_POZOS_ACTUAL T WHERE NOT EXISTS(SELECT 1 FROM #Nueva N WHERE N.POZO_CLAVE=T.POZO_CLAVE);

    DECLARE @DiaFoto date=CONVERT(date,DATEADD(second,-@SegCorte,@Foto)),@IniFoto datetime2(0),@FinFoto datetime2(0),
     @Total int,@SinCom int,@Com int,@Inter int,@SinDato int,@Falla int,@Brecha int;
    SET @IniFoto=DATEADD(second,@SegCorte,CONVERT(datetime2(0),@DiaFoto));
    SET @FinFoto=DATEADD(day,1,@IniFoto);
    SELECT @Total=COUNT(*),@SinCom=SUM(CASE WHEN COMUNICACION=N'Sin comunicación' THEN 1 ELSE 0 END),
     @Com=SUM(CASE WHEN COMUNICACION=N'Comunicando' THEN 1 ELSE 0 END),
     @Inter=SUM(CASE WHEN COMUNICACION=N'Intermitente' THEN 1 ELSE 0 END),
     @SinDato=SUM(CASE WHEN COMUNICACION=N'Sin dato' THEN 1 ELSE 0 END),
     @Falla=SUM(CASE WHEN ESTADO=N'En falla' THEN 1 ELSE 0 END) FROM #Nueva;
    SET @Brecha=CASE WHEN @Anterior IS NULL THEN @Edad+1
     ELSE (DATEDIFF(second,@Anterior,@Foto)+59)/60 END;
    /* Solo dias cerrados con principio, fin y sin brechas se habilitan para KPI.
       El primer dia incompleto de instalacion permanece incompleto. */
    UPDATE D SET COBERTURA_COMPLETA=CASE WHEN D.HORA_CORTE=@Corte AND D.BRECHA_MAX_MIN<=@Edad
      AND D.FECHA_PRIMERA_MUESTRA<=DATEADD(minute,@Edad,DATEADD(second,@SegCorte,CONVERT(datetime2(0),D.DIA_OPERATIVO)))
      AND D.FECHA_ULTIMA_MUESTRA>=DATEADD(minute,-@Edad,DATEADD(day,1,DATEADD(second,@SegCorte,CONVERT(datetime2(0),D.DIA_OPERATIVO))))
      AND @Foto<=DATEADD(minute,@Edad,DATEADD(day,1,DATEADD(second,@SegCorte,CONVERT(datetime2(0),D.DIA_OPERATIVO))))
      AND DATEDIFF(second,D.FECHA_ULTIMA_MUESTRA,@Foto)<=@Edad*60
      THEN 1 ELSE 0 END
    FROM dbo.CLEAR_DASH_POZOS_DIARIO D WHERE D.DIA_OPERATIVO<@DiaFoto AND D.COBERTURA_COMPLETA=0
     AND D.DIA_OPERATIVO>=DATEADD(day,-1,@DiaFoto);
    IF EXISTS(SELECT 1 FROM dbo.CLEAR_DASH_POZOS_DIARIO WHERE DIA_OPERATIVO=@DiaFoto)
     UPDATE dbo.CLEAR_DASH_POZOS_DIARIO SET FECHA_ULTIMA_MUESTRA=@Foto,TOTAL=@Total,SIN_COM=@SinCom,
      COMUNICANDO=@Com,INTERMITENTE=@Inter,SIN_DATO=@SinDato,EN_FALLA=@Falla,MUESTRAS=MUESTRAS+1,
      BRECHA_MAX_MIN=CASE WHEN HORA_CORTE<>@Corte OR @Completa=0 THEN 2147483647
       WHEN @Brecha>BRECHA_MAX_MIN THEN @Brecha ELSE BRECHA_MAX_MIN END,COBERTURA_COMPLETA=0
     WHERE DIA_OPERATIVO=@DiaFoto;
    ELSE
     INSERT dbo.CLEAR_DASH_POZOS_DIARIO
      (DIA_OPERATIVO,FECHA_PRIMERA_MUESTRA,FECHA_ULTIMA_MUESTRA,TOTAL,SIN_COM,COMUNICANDO,INTERMITENTE,SIN_DATO,EN_FALLA,MUESTRAS,COBERTURA_COMPLETA,HORA_CORTE,BRECHA_MAX_MIN)
     VALUES(@DiaFoto,@Foto,@Foto,@Total,@SinCom,@Com,@Inter,@SinDato,@Falla,1,0,@Corte,
      CASE WHEN @Completa=0 THEN 2147483647
       WHEN @Anterior IS NULL THEN (DATEDIFF(second,@IniFoto,@Foto)+59)/60 ELSE @Brecha END);
   END;
   UPDATE dbo.CLEAR_DASH_POZOS_ESTADO_FUENTES SET
    FECHA_TELEMETRIA=CASE WHEN @TelemetriaOk=1 AND (@Anterior IS NULL OR @Foto>@Anterior) THEN @Foto ELSE FECHA_TELEMETRIA END,
    FECHA_FALLAS=CASE WHEN @FallasOk=1 THEN @Ahora ELSE FECHA_FALLAS END,
    FALLAS_DISPONIBLES=@FallasOk,DIA_OPERATIVO_FALLAS=CASE WHEN @FallasOk=1 THEN @Dia ELSE DIA_OPERATIVO_FALLAS END,
    MENSAJE=NULLIF(@Mensaje,N'') WHERE ID=1;
   DELETE TOP(500) FROM dbo.CLEAR_DASH_POZOS_DIARIO WHERE DIA_OPERATIVO<DATEADD(day,-@Dias,@Dia);
   DELETE TOP(5000) FROM dbo.CLEAR_DASH_POZOS_FALLAS_DIA WHERE DIA_OPERATIVO<DATEADD(day,-7,@Dia);
  COMMIT TRANSACTION;
  IF @FallasOk=0 OR @TelemetriaOk=0 THROW 51204,@Mensaje,1;
  EXEC sys.sp_releaseapplock @Resource=N'CLEAR_DASH_POZOS_REFRESCAR',@LockOwner=N'Session';
 END TRY
 BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK TRANSACTION;
  EXEC sys.sp_releaseapplock @Resource=N'CLEAR_DASH_POZOS_REFRESCAR',@LockOwner=N'Session';
  THROW;
 END CATCH;
END;
