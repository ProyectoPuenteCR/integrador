/*
  CLEAR - CONFIGURACION GLOBAL DEL ESTADO CFN
  Fecha: 2026-09-08

  Modos disponibles:
    OCULTAR_ESTADO : conserva las filas (incluidas las FALLA) y oculta CFN.
    MOSTRAR        : conserva las filas y muestra CFN como estado.
    EXCLUIR        : excluye completamente las filas cuyo estado es CFN.

  La web solamente registra una solicitud. SQL Agent procesa una única cola,
  en orden y con paralelismo limitado. dbo.FIXALARMS nunca se modifica.
*/

