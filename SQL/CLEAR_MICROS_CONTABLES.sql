/* 4. Sincroniza históricos sin pisar filas ya editadas por un usuario. */
CREATE OR ALTER PROCEDURE dbo.SP_CLEAR_SINCRONIZAR_MICROS_CONTABLES
    @FechaDesde DATE = NULL,
    @FechaHasta DATE = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    IF @FechaDesde IS NULL SET @FechaDesde=(SELECT MIN(FECHA_DATO) FROM dbo.MASICOS_SC_HISTORICO);
    IF @FechaHasta IS NULL SET @FechaHasta=(SELECT MAX(FECHA_DATO) FROM dbo.MASICOS_SC_HISTORICO);
    IF @FechaDesde IS NULL OR @FechaHasta IS NULL RETURN;

    ;WITH FUENTE AS
    (
        SELECT
            H.*,
            S.ZONA AS ZONA_AUTO,
            S.SUPERVISOR AS SUPERVISOR_AUTO,
            S.JEFE_ZONA AS JEFE_AUTO
        FROM dbo.MASICOS_SC_HISTORICO H
        OUTER APPLY
        (
            SELECT TOP (1) X.ZONA,X.SUPERVISOR,X.JEFE_ZONA
            FROM dbo.CLEAR_SUPERVISORES_INSTALACIONES X
            WHERE X.ACTIVO=1
              AND dbo.FN_CLEAR_NORMALIZAR_BATERIA(X.BATERIA,0)=dbo.FN_CLEAR_NORMALIZAR_BATERIA(H.BATERIA,1)
            ORDER BY X.ID
        ) S
        WHERE H.FECHA_DATO BETWEEN @FechaDesde AND @FechaHasta
    )
    MERGE dbo.CLEAR_MICROS_CONTABLES AS T
    USING FUENTE AS S
       ON T.ORIGEN=N'MASICOS'
      AND T.FECHA_DATO=S.FECHA_DATO
      AND ISNULL(T.[Name],N'')=ISNULL(S.[Name],N'') COLLATE DATABASE_DEFAULT
      AND ISNULL(T.BATERIA,N'')=ISNULL(S.BATERIA,N'') COLLATE DATABASE_DEFAULT
    WHEN MATCHED THEN
        UPDATE SET
            T.MASICO_HISTORICO_ID=S.ID,
            T.FECHA_INSERCION_MASICO=S.FECHA_INSERCION,
            T.NOMBRE_INSTALACION=CASE WHEN T.EDITADO_MANUAL=0 THEN S.NOMBRE_INSTALACION ELSE T.NOMBRE_INSTALACION END,
            T.BATERIA=CASE WHEN T.EDITADO_MANUAL=0 THEN S.BATERIA ELSE T.BATERIA END,
            T.ZONA=CASE WHEN T.EDITADO_MANUAL=0 THEN S.ZONA_AUTO ELSE T.ZONA END,
            T.MODALIDAD=CASE
                WHEN T.EDITADO_MANUAL=1 THEN T.MODALIDAD
                WHEN ABS(ISNULL(S.FT001,0))>0 THEN N'POR MEDIDOR'
                ELSE N'PRODUCCION TEORICA'
            END,
            T.FT001=CASE WHEN T.EDITADO_MANUAL=0 THEN S.FT001 ELSE T.FT001 END,
            T.ACUM_BRUTA=CASE WHEN T.EDITADO_MANUAL=0 THEN S.ACUM_BRUTA ELSE T.ACUM_BRUTA END,
            T.PROY_BRUTA=CASE WHEN T.EDITADO_MANUAL=0 THEN S.PROY_BRUTA ELSE T.PROY_BRUTA END,
            T.CAUDAL_INSTANTANEO=CASE WHEN T.EDITADO_MANUAL=0 THEN S.CAUDAL_INSTANTANEO ELSE T.CAUDAL_INSTANTANEO END,
            T.PROY_NETA=CASE WHEN T.EDITADO_MANUAL=0 THEN S.PROY_NETA ELSE T.PROY_NETA END,
            T.ACUM_NETA=CASE WHEN T.EDITADO_MANUAL=0 THEN S.ACUM_NETA ELSE T.ACUM_NETA END,
            T.LT001=CASE WHEN T.EDITADO_MANUAL=0 THEN S.LT001 ELSE T.LT001 END,
            T.PROMEDIO_BRUTA_7_DIAS=CASE WHEN T.EDITADO_MANUAL=0 THEN S.PROMEDIO_BRUTA_7_DIAS ELSE T.PROMEDIO_BRUTA_7_DIAS END,
            T.PLC001=CASE WHEN T.EDITADO_MANUAL=0 THEN S.PLC001 ELSE T.PLC001 END,
            T.SUPERVISOR=CASE WHEN T.EDITADO_MANUAL=0 THEN S.SUPERVISOR_AUTO ELSE T.SUPERVISOR END,
            T.JEFE_ZONA=CASE WHEN T.EDITADO_MANUAL=0 THEN S.JEFE_AUTO ELSE T.JEFE_ZONA END,
            T.ACTIVO=CASE WHEN T.EDITADO_MANUAL=0 THEN 1 ELSE T.ACTIVO END,
            T.FECHA_MODIFICACION=CASE WHEN T.EDITADO_MANUAL=0 THEN SYSDATETIME() ELSE T.FECHA_MODIFICACION END,
            T.USUARIO_MODIFICACION=CASE WHEN T.EDITADO_MANUAL=0 THEN N'SISTEMA' ELSE T.USUARIO_MODIFICACION END
    WHEN NOT MATCHED THEN
        INSERT
        (
            MASICO_HISTORICO_ID,ORIGEN,EDITADO_MANUAL,FECHA_DATO,FECHA_INSERCION_MASICO,
            [Name],NOMBRE_INSTALACION,BATERIA,ZONA,MODALIDAD,FT001,ACUM_BRUTA,PROY_BRUTA,
            CAUDAL_INSTANTANEO,PROY_NETA,ACUM_NETA,LT001,PROMEDIO_BRUTA_7_DIAS,PLC001,
            SUPERVISOR,JEFE_ZONA,ACTIVO,USUARIO_ALTA,USUARIO_MODIFICACION
        )
        VALUES
        (
            S.ID,N'MASICOS',0,S.FECHA_DATO,S.FECHA_INSERCION,S.[Name],S.NOMBRE_INSTALACION,
            S.BATERIA,S.ZONA_AUTO,
            CASE WHEN ABS(ISNULL(S.FT001,0))>0 THEN N'POR MEDIDOR' ELSE N'PRODUCCION TEORICA' END,
            S.FT001,S.ACUM_BRUTA,S.PROY_BRUTA,S.CAUDAL_INSTANTANEO,S.PROY_NETA,S.ACUM_NETA,
            S.LT001,S.PROMEDIO_BRUTA_7_DIAS,S.PLC001,S.SUPERVISOR_AUTO,S.JEFE_AUTO,
            1,N'SISTEMA',N'SISTEMA'
        );
END;
GO

/* 5. Carga diaria corregida y sincronización automática. */
CREATE OR ALTER PROCEDURE dbo.SP_CARGAR_MASICOS_SC_DIARIO
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    DECLARE @FechaInsercion DATETIME2(0)=SYSDATETIME();
    DECLARE @FechaDato DATE=CONVERT(date,@FechaInsercion);
    DECLARE @Cantidad INT;

    CREATE TABLE #CargaMasicos
    (
        [Name] NVARCHAR(255) COLLATE DATABASE_DEFAULT NULL,
        NOMBRE_INSTALACION NVARCHAR(255) COLLATE DATABASE_DEFAULT NULL,
        BATERIA NVARCHAR(100) COLLATE DATABASE_DEFAULT NULL,
        FT001 DECIMAL(18,3) NULL,ACUM_BRUTA DECIMAL(18,3) NULL,PROY_BRUTA DECIMAL(18,3) NULL,
        CAUDAL_INSTANTANEO DECIMAL(18,3) NULL,PROY_NETA DECIMAL(18,3) NULL,
        ACUM_NETA DECIMAL(18,3) NULL,LT001 DECIMAL(18,3) NULL,
        PROMEDIO_BRUTA_7_DIAS DECIMAL(18,3) NULL,
        PLC001 NVARCHAR(100) COLLATE DATABASE_DEFAULT NULL
    );

    INSERT #CargaMasicos
    SELECT [Name],NOMBRE_INSTALACION,BATERIA,FT001,ACUM_BRUTA,PROY_BRUTA,
           CAUDAL_INSTANTANEO,PROY_NETA,ACUM_NETA,LT001,PROMEDIO_BRUTA_7_DIAS,PLC001
    FROM dbo.MASICOS_SC;

    SET @Cantidad=@@ROWCOUNT;
    IF @Cantidad=0
        THROW 51001, N'La vista dbo.MASICOS_SC no devolvió registros. Se conservó la carga existente.', 1;

    BEGIN TRY
        BEGIN TRANSACTION;
        DELETE dbo.MASICOS_SC_HISTORICO WHERE FECHA_DATO=@FechaDato;

        INSERT dbo.MASICOS_SC_HISTORICO
        (
            FECHA_DATO,FECHA_INSERCION,[Name],NOMBRE_INSTALACION,BATERIA,FT001,ACUM_BRUTA,
            PROY_BRUTA,CAUDAL_INSTANTANEO,PROY_NETA,ACUM_NETA,LT001,PROMEDIO_BRUTA_7_DIAS,PLC001
        )
        SELECT @FechaDato,@FechaInsercion,[Name],NOMBRE_INSTALACION,BATERIA,FT001,ACUM_BRUTA,
               PROY_BRUTA,CAUDAL_INSTANTANEO,PROY_NETA,ACUM_NETA,LT001,PROMEDIO_BRUTA_7_DIAS,PLC001
        FROM #CargaMasicos;
        COMMIT TRANSACTION;

        EXEC dbo.SP_CLEAR_SINCRONIZAR_MICROS_CONTABLES @FechaDato,@FechaDato;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT>0 ROLLBACK TRANSACTION;
        THROW;
    END CATCH;

    SELECT @FechaDato FECHA_DATO,@FechaInsercion FECHA_INSERCION,@Cantidad REGISTROS_GUARDADOS;
END;
GO

