/* Normalización común de baterías.
   @EsMasico=1 elimina el prefijo técnico B:
   BCE008 -> CE8, BBB002 -> BB2, BCG005 -> CG5.
   @EsMasico=0 conserva el código maestro:
   CE 08 -> CE8, BB 02 -> BB2, CG 05 -> CG5. */
CREATE OR ALTER FUNCTION dbo.FN_CLEAR_NORMALIZAR_BATERIA
(
    @Valor NVARCHAR(255),
    @EsMasico BIT
)
RETURNS NVARCHAR(255)
AS
BEGIN
    DECLARE @Clave NVARCHAR(255)=UPPER(LTRIM(RTRIM(ISNULL(@Valor,N''))));
    SET @Clave=REPLACE(REPLACE(REPLACE(REPLACE(REPLACE(@Clave,N' ',N''),N'-',N''),N'_',N''),N'.',N''),N'/',N'');

    IF @EsMasico=1 AND LEN(@Clave)>1 AND LEFT(@Clave,1)=N'B'
        SET @Clave=SUBSTRING(@Clave,2,255);

    DECLARE @PosNumero INT=PATINDEX(N'%[0-9]%',@Clave);
    IF @PosNumero>1
    BEGIN
        DECLARE @Prefijo NVARCHAR(100)=LEFT(@Clave,@PosNumero-1);
        DECLARE @NumeroTexto NVARCHAR(100)=SUBSTRING(@Clave,@PosNumero,100);
        DECLARE @Numero BIGINT=TRY_CONVERT(BIGINT,@NumeroTexto);
        IF @Numero IS NOT NULL SET @Clave=@Prefijo+CONVERT(NVARCHAR(30),@Numero);
    END;

    RETURN @Clave;
END;
GO

