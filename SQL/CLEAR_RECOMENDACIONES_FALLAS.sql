-- Ejecutar en la misma base de datos de CLEAR. Reejecutable; no elimina datos.
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID(N'dbo.CLEAR_RECOMENDACIONES_FALLAS', N'U') IS NULL
BEGIN
 CREATE TABLE dbo.CLEAR_RECOMENDACIONES_FALLAS (
  ID int IDENTITY(1,1) NOT NULL PRIMARY KEY,
  TOKEN char(48) NOT NULL UNIQUE,
  TIPO nvarchar(20) NOT NULL CHECK (TIPO IN (N'Recomendación',N'Falla')),
  NOMBRE nvarchar(150) NOT NULL,
  FECHA date NOT NULL,
  EMAIL nvarchar(254) NOT NULL,
  TITULO nvarchar(200) NOT NULL,
  COMENTARIO nvarchar(max) NOT NULL,
  USUARIO_CARGA nvarchar(255) NOT NULL,
  FECHA_CARGA datetime2(3) NOT NULL DEFAULT SYSDATETIME(),
  USUARIO_MODIFICACION nvarchar(255) NULL,
  FECHA_MODIFICACION datetime2(3) NULL,
  ELIMINADO bit NOT NULL DEFAULT 0,
  EMAIL_ESTADO varchar(20) NOT NULL DEFAULT 'PENDIENTE',
  EMAIL_ERROR nvarchar(1000) NULL,
  EMAIL_FECHA datetime2(3) NULL
 );
 CREATE INDEX IX_CLEAR_RF_FECHA ON dbo.CLEAR_RECOMENDACIONES_FALLAS(ELIMINADO,FECHA_CARGA DESC,ID DESC);
END;
IF OBJECT_ID(N'dbo.CLEAR_RF_CONFIG', N'U') IS NULL
BEGIN
 CREATE TABLE dbo.CLEAR_RF_CONFIG (
  ID int NOT NULL PRIMARY KEY CHECK(ID=1),
  DESTINATARIOS nvarchar(4000) NOT NULL DEFAULT N'',
  ACTUALIZADO_POR nvarchar(255) NULL,
  ACTUALIZADO_EN datetime2(3) NOT NULL DEFAULT SYSDATETIME()
 );
END;
IF NOT EXISTS(SELECT 1 FROM dbo.CLEAR_RF_CONFIG WHERE ID=1)
 INSERT dbo.CLEAR_RF_CONFIG(ID,DESTINATARIOS) VALUES(1,N'');
COMMIT;
-- La identidad SQL de IIS necesita SELECT, INSERT y UPDATE sobre ambas tablas.
-- No necesita CREATE/ALTER ni DELETE: el borrado es lógico y conserva la auditoría.
