/* Ejecutar en la base de la plataforma CLEAR. No modifica tablas SCADA ni PI. */
SET XACT_ABORT ON;
BEGIN TRANSACTION;
IF OBJECT_ID(N'dbo.CLEAR_CARTAS_CARGAS',N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CLEAR_CARTAS_CARGAS (
        ID uniqueidentifier NOT NULL PRIMARY KEY,
        CORTE datetime2(0) NOT NULL, -- Hora Argentina, siempre 06:00
        INICIO datetime2(0) NOT NULL DEFAULT SYSDATETIME(),
        FIN datetime2(0) NULL,
        ESTADO varchar(12) NOT NULL CHECK (ESTADO IN ('CARGANDO','COMPLETA','ERROR')),
        POZOS int NOT NULL DEFAULT 0,
        ADVERTENCIAS int NOT NULL DEFAULT 0,
        DETALLE nvarchar(1000) NOT NULL DEFAULT N''
    );
    CREATE INDEX IX_CLEAR_CARTAS_CARGAS_CORTE ON dbo.CLEAR_CARTAS_CARGAS(ESTADO,CORTE DESC,FIN DESC);
END;
IF OBJECT_ID(N'dbo.CLEAR_CARTAS_DIARIAS',N'U') IS NULL
BEGIN
    CREATE TABLE dbo.CLEAR_CARTAS_DIARIAS (
        CARGA_ID uniqueidentifier NOT NULL,
        POZO nvarchar(180) NOT NULL,
        BATERIA nvarchar(255) NOT NULL,
        TIPO varchar(12) NOT NULL CHECK (TIPO IN ('superficie','fondo')),
        REFERENCIA datetime2(0) NULL, -- Fecha de la carta, hora Argentina
        CARTA_JSON nvarchar(max) NULL,
        OBSERVACION nvarchar(1000) NOT NULL DEFAULT N'',
        CONSTRAINT PK_CLEAR_CARTAS_DIARIAS PRIMARY KEY(CARGA_ID,POZO,TIPO),
        CONSTRAINT FK_CLEAR_CARTAS_DIARIAS_CARGA FOREIGN KEY(CARGA_ID) REFERENCES dbo.CLEAR_CARTAS_CARGAS(ID)
    );
    CREATE INDEX IX_CLEAR_CARTAS_DIARIAS_BATERIA ON dbo.CLEAR_CARTAS_DIARIAS(CARGA_ID,BATERIA,POZO);
END;
COMMIT;
