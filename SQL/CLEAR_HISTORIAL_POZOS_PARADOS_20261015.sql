/*
 CLEAR - Historial de Pozos Parados
 Los eventos se detectan desde CLEAR_POZOS_PARADOS_CACHE, no desde la web.
 Se conserva el historico de snapshots usado para perdida 24 horas.
 Retencion: 30 dias (configurable 7..365); abiertos nunca se purgan.
 Inicio detectado con frecuencia del job (10 minutos); recuperacion estimada
 tras dos verificaciones separadas por al menos 8 minutos.
*/
SET NOCOUNT ON;
GO
IF OBJECT_ID(N'dbo.CLEAR_HIST_PAROS_CONFIG',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.CLEAR_HIST_PAROS_CONFIG(
 ID tinyint NOT NULL CONSTRAINT PK_CLEAR_HIST_PAROS_CONFIG PRIMARY KEY
   CONSTRAINT CK_CLEAR_HIST_PAROS_CONFIG_ID CHECK(ID=1),
 RETENCION_DIAS smallint NOT NULL CONSTRAINT DF_CLEAR_HIST_PAROS_DIAS DEFAULT(30)
   CONSTRAINT CK_CLEAR_HIST_PAROS_DIAS CHECK(RETENCION_DIAS BETWEEN 7 AND 365),
 MODIFICADO_POR nvarchar(150) NOT NULL CONSTRAINT DF_CLEAR_HIST_PAROS_USER DEFAULT(N'SISTEMA'),
 FECHA_MODIFICACION datetime2(0) NOT NULL CONSTRAINT DF_CLEAR_HIST_PAROS_MOD DEFAULT(SYSDATETIME()));
END;
IF NOT EXISTS(SELECT 1 FROM dbo.CLEAR_HIST_PAROS_CONFIG WHERE ID=1)
 INSERT INTO dbo.CLEAR_HIST_PAROS_CONFIG(ID,RETENCION_DIAS) VALUES(1,30);
GO
IF OBJECT_ID(N'dbo.CLEAR_HIST_PAROS_EVENTOS',N'U') IS NULL
BEGIN
 CREATE TABLE dbo.CLEAR_HIST_PAROS_EVENTOS(
 ID bigint IDENTITY(1,1) NOT NULL CONSTRAINT PK_CLEAR_HIST_PAROS_EVENTOS PRIMARY KEY CLUSTERED,
 SISTEMA nvarchar(20) NOT NULL,
 POZO_CLAVE nvarchar(100) NOT NULL,
 POZO nvarchar(255) NOT NULL,
 BATERIA nvarchar(255) NULL,
 ESTADO_POZO nvarchar(40) NULL,
 ESTADO_TELEMETRIA nvarchar(255) NULL,
 ESTADO_ZAFIRO nvarchar(500) NULL,
 METODO_ZAFIRO nvarchar(500) NULL,
 FECHA_INICIO datetime2(0) NOT NULL,
 FECHA_FIN datetime2(0) NULL,
 FECHA_DATO_ORIGEN datetime2(0) NULL,
 PRODUCCION_PETROLEO decimal(18,3) NULL,
 PRODUCCION_AGUA decimal(18,3) NULL,
 FECHA_TEST datetime2(0) NULL,
 AUSENCIAS_CONSECUTIVAS tinyint NOT NULL CONSTRAINT DF_CLEAR_HIST_PAROS_AUSENCIAS DEFAULT(0),
 FECHA_ULTIMA_AUSENCIA datetime2(0) NULL,
 CONSTRAINT CK_CLEAR_HIST_PAROS_FECHAS CHECK(FECHA_FIN IS NULL OR FECHA_FIN>=FECHA_INICIO));
END;
GO
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.CLEAR_HIST_PAROS_EVENTOS') AND name=N'UX_CLEAR_HIST_PAROS_ABIERTOS')
 CREATE UNIQUE NONCLUSTERED INDEX UX_CLEAR_HIST_PAROS_ABIERTOS
 ON dbo.CLEAR_HIST_PAROS_EVENTOS(SISTEMA,POZO_CLAVE)
 INCLUDE(ID,FECHA_INICIO,AUSENCIAS_CONSECUTIVAS,FECHA_ULTIMA_AUSENCIA)
 WHERE FECHA_FIN IS NULL;
GO
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.CLEAR_HIST_PAROS_EVENTOS') AND name=N'IX_CLEAR_HIST_PAROS_CONSULTA')
 CREATE NONCLUSTERED INDEX IX_CLEAR_HIST_PAROS_CONSULTA
 ON dbo.CLEAR_HIST_PAROS_EVENTOS(FECHA_INICIO DESC,ID DESC)
 INCLUDE(FECHA_FIN,PRODUCCION_PETROLEO,PRODUCCION_AGUA);
GO
IF NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.CLEAR_HIST_PAROS_EVENTOS') AND name=N'IX_CLEAR_HIST_PAROS_PURGA')
 CREATE NONCLUSTERED INDEX IX_CLEAR_HIST_PAROS_PURGA
 ON dbo.CLEAR_HIST_PAROS_EVENTOS(FECHA_FIN) WHERE FECHA_FIN IS NOT NULL;
GO
/* El indice Q164 solamente se crea si aun no existe. */
IF OBJECT_ID(N'dbo.CLEAR_API_Q164_CACHE',N'U') IS NOT NULL
 AND NOT EXISTS(SELECT 1 FROM sys.indexes WHERE object_id=OBJECT_ID(N'dbo.CLEAR_API_Q164_CACHE') AND name=N'IX_CLEAR_API_Q164_CACHE_POZO_FECHA')
 CREATE NONCLUSTERED INDEX IX_CLEAR_API_Q164_CACHE_POZO_FECHA
 ON dbo.CLEAR_API_Q164_CACHE(POZO,DIA_OPERATIVO DESC,FECHA_HORA DESC,ID_TEST DESC)
 INCLUDE(PRODUCCION_PETROLEO,PRODUCCION_LIQUIDO);
GO
CREATE OR ALTER PROCEDURE dbo.SP_CLEAR_HIST_PAROS_CONFIGURAR
 @RetencionDias smallint, @Usuario nvarchar(150)
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 IF @RetencionDias NOT BETWEEN 7 AND 365
   THROW 51101,N'La retencion debe estar entre 7 y 365 dias.',1;
 UPDATE dbo.CLEAR_HIST_PAROS_CONFIG
 SET RETENCION_DIAS=@RetencionDias,
 MODIFICADO_POR=COALESCE(NULLIF(LTRIM(RTRIM(@Usuario)),N''),N'ADMIN'),
 FECHA_MODIFICACION=SYSDATETIME()
 WHERE ID=1;
END;
GO
CREATE OR ALTER PROCEDURE dbo.SP_CLEAR_HIST_PAROS_SINCRONIZAR
AS
BEGIN
 SET NOCOUNT ON; SET XACT_ABORT ON;
 DECLARE @Ahora datetime2(0)=SYSDATETIME();
 DECLARE @UltimaCache datetime2(0),@ParadosActuales bigint=0,
 @Abiertos bigint=0,@CacheGeneralFecha datetime2(0),
 @CacheGeneralPozos bigint=0,@PuedeCerrar bit=0,
 @Dias smallint=30,@LockResult int;

 /* No consulta RTQP: el job preexistente ya actualizo la cache. */
 IF OBJECT_ID(N'dbo.CLEAR_POZOS_PARADOS_CACHE',N'U') IS NULL RETURN;
 SELECT @ParadosActuales=COUNT_BIG(*),@UltimaCache=MAX(FECHA_CACHE)
 FROM dbo.CLEAR_POZOS_PARADOS_CACHE;
 IF @UltimaCache IS NOT NULL AND @UltimaCache<DATEADD(minute,-30,@Ahora) RETURN;

 /* Cero parados por si solo no confirma recuperacion: requiere telemetria fresca. */
 IF OBJECT_ID(N'dbo.TELEMETRIA_POZOS_GENERAL_CACHE',N'U') IS NOT NULL
 BEGIN
  SELECT @CacheGeneralFecha=MAX(FECHA_CACHE),@CacheGeneralPozos=COUNT_BIG(*)
  FROM dbo.TELEMETRIA_POZOS_GENERAL_CACHE;
 END;
 IF @ParadosActuales=0 AND NOT(
   @CacheGeneralPozos>=100 AND @CacheGeneralFecha>=DATEADD(minute,-30,@Ahora)
 ) RETURN;

 BEGIN TRY
  BEGIN TRANSACTION;
  EXEC @LockResult=sys.sp_getapplock
   @Resource=N'CLEAR_HIST_PAROS_SINCRONIZAR',
   @LockMode=N'Exclusive',@LockOwner=N'Transaction',@LockTimeout=0;
  IF @LockResult<0 BEGIN ROLLBACK TRANSACTION; RETURN; END;

  SELECT @Dias=RETENCION_DIAS FROM dbo.CLEAR_HIST_PAROS_CONFIG WHERE ID=1;
  SET @Dias=ISNULL(@Dias,30);
  SELECT @Abiertos=COUNT_BIG(*) FROM dbo.CLEAR_HIST_PAROS_EVENTOS WHERE FECHA_FIN IS NULL;

  /* Una desaparicion masiva sospechosa NO se considera recuperacion. */
  SET @PuedeCerrar=CASE
   WHEN @Abiertos>=10 AND @ParadosActuales=0 THEN 0
   WHEN @ParadosActuales=0 AND @CacheGeneralPozos>=100
    AND @CacheGeneralFecha>=DATEADD(minute,-30,@Ahora) THEN 1
   WHEN @Abiertos>=10 AND @ParadosActuales*10<@Abiertos*3 THEN 0
   ELSE 1 END;

  CREATE TABLE #Nuevos(
   ID bigint NOT NULL PRIMARY KEY,
   POZO nvarchar(255) COLLATE DATABASE_DEFAULT NOT NULL);

  INSERT INTO dbo.CLEAR_HIST_PAROS_EVENTOS
   (SISTEMA,POZO_CLAVE,POZO,BATERIA,ESTADO_POZO,ESTADO_TELEMETRIA,
    ESTADO_ZAFIRO,METODO_ZAFIRO,FECHA_INICIO,FECHA_DATO_ORIGEN)
  OUTPUT inserted.ID,inserted.POZO INTO #Nuevos(ID,POZO)
  SELECT C.SISTEMA,C.POZO_CLAVE,C.POZO,C.BATERIA,C.ESTADO_POZO,
   C.ESTADO_TELEMETRIA,C.ESTADO_ZAFIRO,C.METODO_ZAFIRO,@Ahora,C.FECHA_DATO
  FROM dbo.CLEAR_POZOS_PARADOS_CACHE C
  WHERE C.ESTADO_POZO IN(N'PARADO',N'PARO REAL',N'PARO CONTROLADO',N'PROBABLE PARO')
   AND NOT EXISTS(
    SELECT 1 FROM dbo.CLEAR_HIST_PAROS_EVENTOS E WITH(UPDLOCK,HOLDLOCK,INDEX(UX_CLEAR_HIST_PAROS_ABIERTOS))
    WHERE E.SISTEMA=C.SISTEMA AND E.POZO_CLAVE=C.POZO_CLAVE AND E.FECHA_FIN IS NULL);

  /* SOLO al abrir paro: Q164 indexado. Agua = liquido menos petroleo. */
  IF EXISTS(SELECT 1 FROM #Nuevos)
     AND OBJECT_ID(N'dbo.CLEAR_API_Q164_CACHE',N'U') IS NOT NULL
  BEGIN
   UPDATE E SET
    PRODUCCION_PETROLEO=Q.PETROLEO,
    PRODUCCION_AGUA=CASE
     WHEN Q.LIQUIDO IS NULL OR Q.PETROLEO IS NULL THEN NULL
     WHEN Q.LIQUIDO<Q.PETROLEO THEN CONVERT(decimal(18,3),0)
     ELSE Q.LIQUIDO-Q.PETROLEO END,
    FECHA_TEST=Q.FECHA_TEST
   FROM dbo.CLEAR_HIST_PAROS_EVENTOS E
   INNER JOIN #Nuevos N ON N.ID=E.ID
   OUTER APPLY(
    SELECT TOP(1)
     TRY_CONVERT(decimal(18,3),T.PRODUCCION_PETROLEO) PETROLEO,
     TRY_CONVERT(decimal(18,3),T.PRODUCCION_LIQUIDO) LIQUIDO,
     TRY_CONVERT(datetime2(0),T.FECHA_HORA) FECHA_TEST
    FROM dbo.CLEAR_API_Q164_CACHE T
    WHERE T.POZO=N.POZO OR T.POZO=REPLACE(N.POZO,N'YPF.SC.',N'')
    ORDER BY T.DIA_OPERATIVO DESC,T.FECHA_HORA DESC,T.ID_TEST DESC
   ) Q;
  END;

  /* Si reaparece un paro no se crea otro evento, se anula la ausencia. */
  UPDATE E SET AUSENCIAS_CONSECUTIVAS=0,FECHA_ULTIMA_AUSENCIA=NULL
  FROM dbo.CLEAR_HIST_PAROS_EVENTOS E
  WHERE E.FECHA_FIN IS NULL AND E.AUSENCIAS_CONSECUTIVAS<>0
    AND EXISTS(SELECT 1 FROM dbo.CLEAR_POZOS_PARADOS_CACHE C
     WHERE C.SISTEMA=E.SISTEMA AND C.POZO_CLAVE=E.POZO_CLAVE);

  IF @PuedeCerrar=1
  BEGIN
   UPDATE E SET
    AUSENCIAS_CONSECUTIVAS=CASE WHEN E.AUSENCIAS_CONSECUTIVAS<2
      THEN E.AUSENCIAS_CONSECUTIVAS+1 ELSE 2 END,
    FECHA_ULTIMA_AUSENCIA=@Ahora
   FROM dbo.CLEAR_HIST_PAROS_EVENTOS E
   WHERE E.FECHA_FIN IS NULL AND E.AUSENCIAS_CONSECUTIVAS<2
    AND (E.FECHA_ULTIMA_AUSENCIA IS NULL
       OR E.FECHA_ULTIMA_AUSENCIA<=DATEADD(minute,-8,@Ahora))
    AND NOT EXISTS(SELECT 1 FROM dbo.CLEAR_POZOS_PARADOS_CACHE C
     WHERE C.SISTEMA=E.SISTEMA AND C.POZO_CLAVE=E.POZO_CLAVE);

   UPDATE E SET FECHA_FIN=@Ahora
   FROM dbo.CLEAR_HIST_PAROS_EVENTOS E
   WHERE E.FECHA_FIN IS NULL AND E.AUSENCIAS_CONSECUTIVAS>=2
    AND NOT EXISTS(SELECT 1 FROM dbo.CLEAR_POZOS_PARADOS_CACHE C
     WHERE C.SISTEMA=E.SISTEMA AND C.POZO_CLAVE=E.POZO_CLAVE);
  END;

  /* Purga indexada y acotada; los eventos abiertos permanecen. */
  DELETE TOP(1000) FROM dbo.CLEAR_HIST_PAROS_EVENTOS
  WHERE FECHA_FIN IS NOT NULL AND FECHA_FIN<DATEADD(day,-@Dias,@Ahora);
  COMMIT TRANSACTION;
 END TRY
 BEGIN CATCH
  IF @@TRANCOUNT>0 ROLLBACK TRANSACTION;
  THROW;
 END CATCH;
END;
GO
