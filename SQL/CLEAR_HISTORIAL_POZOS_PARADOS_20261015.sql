/* Mantiene mismo job, mismo horario y primer procedimiento existente. */
DECLARE @Paso nvarchar(max);
SELECT @Paso=S.command FROM dbo.sysjobs J
INNER JOIN dbo.sysjobsteps S ON S.job_id=J.job_id AND S.step_id=1
WHERE J.name=N'CLEAR - Reporte Pozos Parados';
IF @Paso IS NOT NULL
BEGIN
 IF CHARINDEX(N'SP_CLEAR_HIST_PAROS_SINCRONIZAR',@Paso)=0
  AND CHARINDEX(N'SP_CLEAR_POZOS_PARADOS_REFRESCAR',@Paso)>0
 BEGIN
  SET @Paso=@Paso+CHAR(10)+N'EXEC dbo.SP_CLEAR_HIST_PAROS_SINCRONIZAR;';
  EXEC dbo.sp_update_jobstep
   @job_name=N'CLEAR - Reporte Pozos Parados',
   @step_id=1,@database_name=N'LC_MDB',@command=@Paso;
 END;
 PRINT N'Job de Pozos Parados actualizado para registrar eventos.';
END
ELSE PRINT N'ATENCION: no se encontro el Job CLEAR - Reporte Pozos Parados.';
GO
